// Record layer nghien cuu: mot phien, hai khoa hai chieu, counter chong replay.
// Kem_clear huy phien khi chay K/E/D/Z moi; epoch chi reset khi reset phan cung.
// op=0 derive session, 1 seal, 2 open. Payload toi da 256 byte.
module channel_session (
    input logic clk,rst_n,kem_clear,kem_valid,kem_mode,kem_encaps,
    input logic [255:0] kem_secret,
    input logic start,request_mode,
    input logic [1:0] op,
    input logic [127:0] session_id_in,tag_in,
    input logic [63:0] sequence_in,
    input logic [8:0] data_length,
    input logic load_we,
    input logic [7:0] load_address,load_data,read_address,
    output logic [7:0] read_data,error_code,
    output logic active,busy,done,
    output logic [63:0] epoch,result_sequence,
    output logic [127:0] session_id,tag_out,
    output logic [255:0] plaintext_hash,
    output logic [8:0] result_length,
    output logic [31:0] tx_count,rx_count,auth_fail_count,replay_count,cycles
);
    typedef enum logic [3:0] {IDLE,K_START,K_WAIT,AAD_PREP,AAD,G_START,G_WAIT,H_REQ,H_CAP,H_START,H_WAIT,FINISH} state_t;
    state_t state;
    logic pending,mode_reg,role_encaps,dec_reg,last_seal;
    logic [255:0] pending_key,key_e,key_d;
    logic [31:0] prefix_e,prefix_d;
    logic [63:0] tx_seq,rx_seq;
    logic [127:0] input_tag;
    logic [8:0] len_reg;
    logic [7:0] index;
    logic [255:0] aad_block;
    // Byte currently presented to the AES-GCM AAD RAM.  Keeping this byte
    // registered removes the wide variable part-select (aad_block[index])
    // from the RAM data-input timing path.
    logic [7:0] aad_byte_q;
    wire dir=dec_reg?role_encaps:!role_encaps;
    wire [255:0] aad_block_next = {session_id,(mode_reg?8'd4:8'd3),{7'd0,dir},
                                   7'd0,len_reg,result_sequence,32'h4d4b4731};
    wire [575:0] material;
    wire [255:0] digest;
    wire kd_done,g_done,g_ok;
    wire [127:0] g_tag;
    wire [7:0] g_read;
    // Local clear registers cut the cross-hierarchy KEM-launch -> crypto fanout.
    // Public output is masked immediately; primitive erasure follows next clock.
    (* maxfan = 32, preserve, dont_merge *) logic session_clear_q;
    // Do not let physical synthesis merge this boundary register into the
    // high-fanout Keccak clear network inside channel_kdf.
    (* maxfan = 32, preserve, dont_merge *) logic clear_kdf_q;
    (* maxfan = 64, preserve *) logic clear_gcm_q;
    // Keep the public-RAM permission local to the session.  In particular,
    // do not let channel_clear (generated by the distant KEM UART FSM) feed
    // the report-byte mux combinationally across the device.
    (* preserve, dont_merge *) logic public_read_valid_q;
    always_ff @(posedge clk) begin
        // A reset leaves one local clear token asserted.  On reset release the
        // child primitives scrub their wide datapaths before any start pulse.
        if (!rst_n) begin
            session_clear_q <= 1'b1;
            clear_kdf_q     <= 1'b1;
            clear_gcm_q     <= 1'b1;
        end else begin
            // Register the cross-hierarchy request before it reaches the wide
            // session state.  A KEM transaction lasts many thousands of
            // clocks, so delaying local erasure by one clock cannot overlap
            // with delivery of the replacement shared secret.
            session_clear_q <= kem_clear;
            clear_kdf_q     <= session_clear_q || state==FINISH;
            clear_gcm_q     <= session_clear_q;
        end
    end
    always_ff @(posedge clk) begin
        if (!rst_n)
            public_read_valid_q <= 1'b0;
        else if (session_clear_q || clear_gcm_q || (state == IDLE && start))
            public_read_valid_q <= 1'b0;
        else if (state == FINISH)
            public_read_valid_q <= last_seal && (error_code == 8'd0);
    end
    // GCM doit giu ciphertext cho UART sau FINISH; chi xoa GCM khi kem_clear.
    channel_kdf u_kdf(.clk(clk),.rst_n(rst_n),.zeroize(clear_kdf_q),
        .start((state==K_START || state==H_START) && !session_clear_q && !clear_kdf_q),.hash_only(state==H_START),
        .mode_1024(mode_reg),.ikm(pending_key),.session_id(session_id),.epoch(epoch),
        .load_we(state==H_CAP),.load_address(index),.load_data(g_read),.hash_length(len_reg),
        .material(material),.digest(digest),.busy(),.done(kd_done));
    aes_gcm_core u_gcm(.clk(clk),.rst_n(rst_n),.zeroize(clear_gcm_q),.start(state==G_START && !session_clear_q && !clear_gcm_q),
        .decrypt(dec_reg),.key(dir?key_d:key_e),.iv({dir?prefix_d:prefix_e,result_sequence}),
        .tag_in(input_tag),.data_length(len_reg),.aad_length(6'd32),
        .load_we((state==AAD)||(state==IDLE&&load_we)),.load_aad(state==AAD),
        .load_address((state==AAD)?index:load_address),
        .load_data((state==AAD)?aad_byte_q:load_data),
        .read_address((state==H_REQ||state==H_CAP)?index:read_address),.read_data(g_read),
        .tag_out(g_tag),.busy(),.done(g_done),.auth_ok(g_ok),.cycles());
    assign read_data=public_read_valid_q ? g_read : 8'd0;
    integer j;
    always_ff @(posedge clk) begin
        if(!rst_n)begin
            state<=IDLE;pending<=0;mode_reg<=0;role_encaps<=0;dec_reg<=0;last_seal<=0;
            pending_key<=0;key_e<=0;key_d<=0;prefix_e<=0;prefix_d<=0;tx_seq<=0;rx_seq<=0;
            input_tag<=0;len_reg<=0;index<=0;aad_block<=0;aad_byte_q<=0;error_code<=0;active<=0;busy<=0;done<=0;
            epoch<=0;result_sequence<=0;session_id<=0;tag_out<=0;plaintext_hash<=0;result_length<=0;
            tx_count<=0;rx_count<=0;auth_fail_count<=0;replay_count<=0;cycles<=0;
        end else if(session_clear_q)begin
            state<=IDLE;pending<=0;pending_key<=0;key_e<=0;key_d<=0;prefix_e<=0;prefix_d<=0;
            tx_seq<=0;rx_seq<=0;active<=0;busy<=0;done<=0;tag_out<=0;plaintext_hash<=0;
            result_length<=0;last_seal<=0;input_tag<=0;aad_block<=0;aad_byte_q<=0;error_code<=0;
        end else begin
            done<=0;
            if(busy)cycles<=cycles+1'b1;
            if(kem_valid)begin pending_key<=kem_secret;pending<=1;mode_reg<=kem_mode;role_encaps<=kem_encaps;end
            case(state)
                IDLE:if(start)begin
                    busy<=1;cycles<=0;error_code<=0;tag_out<=0;plaintext_hash<=0;result_length<=0;last_seal<=0;
                    dec_reg<=(op==2);len_reg<=data_length;input_tag<=tag_in;index<=0;aad_byte_q<=0;
                    if(request_mode!=mode_reg)begin error_code<=8'ha0;state<=FINISH;end
                    else if(op==0)begin
                        if(!pending || epoch==64'hffffffffffffffff)begin error_code<=8'ha0;state<=FINISH;end
                        else begin epoch<=epoch+1'b1;session_id<=session_id_in;active<=0;state<=K_START;end
                    end else if(!active || op==3)begin error_code<=8'ha0;state<=FINISH;end
                    else if(data_length>256)begin error_code<=8'ha3;state<=FINISH;end
                    else if(op==2 && sequence_in!=rx_seq)begin
                        error_code<=8'ha2;replay_count<=replay_count+1'b1;state<=FINISH;
                    end else if((op==1 && tx_seq>=64'hffffffff)||(op==2 && rx_seq>=64'hffffffff))begin
                        error_code<=8'ha6;state<=FINISH;
                    end else begin
                        result_sequence<=(op==1)?tx_seq:sequence_in;
                        // Separate 64-bit replay/limit checks from the 256-bit
                        // AAD register enable and sequence mux.
                        state<=AAD_PREP;
                    end
                end
                K_START:state<=K_WAIT;
                K_WAIT:if(kd_done)begin
                    for(j=0;j<32;j=j+1)begin key_e[255-8*j-:8]<=material[8*j+:8];key_d[255-8*j-:8]<=material[256+8*j+:8];end
                    for(j=0;j<4;j=j+1)begin prefix_e[31-8*j-:8]<=material[512+8*j+:8];prefix_d[31-8*j-:8]<=material[544+8*j+:8];end
                    pending<=0;pending_key<=0;active<=1;tx_seq<=0;rx_seq<=0;state<=FINISH;
                end
                AAD_PREP:begin
                    aad_block<=aad_block_next;
                    // Preload byte 0 while entering AAD.  aes_gcm_core
                    // consumes this registered value on the next edge.
                    aad_byte_q<=aad_block_next[255 -: 8];
                    state<=AAD;
                end
                AAD:if(index==31)begin
                    index<=0;
                    aad_byte_q<=0;
                    state<=G_START;
                end else begin
                    index<=index+1'b1;
                    aad_byte_q<=aad_block[255-8*(index+1'b1)-:8];
                end
                G_START:state<=G_WAIT;
                G_WAIT:if(g_done)begin
                    if(!g_ok)begin error_code<=8'ha1;auth_fail_count<=auth_fail_count+1'b1;state<=FINISH;end
                    else begin
                        result_length<=len_reg;
                        if(!dec_reg)begin tx_seq<=tx_seq+1'b1;tx_count<=tx_count+1'b1;tag_out<=g_tag;last_seal<=1;state<=FINISH;end
                        else begin rx_seq<=rx_seq+1'b1;rx_count<=rx_count+1'b1;index<=0;state<=(len_reg==0)?H_START:H_REQ;end
                    end
                end
                H_REQ:state<=H_CAP;
                H_CAP:if({1'b0,index}+9'd1==len_reg)state<=H_START;else begin index<=index+1'b1;state<=H_REQ;end
                H_START:state<=H_WAIT;
                H_WAIT:if(kd_done)begin plaintext_hash<=digest;state<=FINISH;end
                FINISH:begin busy<=0;done<=1;input_tag<=0;state<=IDLE;end
                default:state<=IDLE;
            endcase
        end
    end
endmodule
